"""LoRA SFT on the story-imprinting stories: the 001 recipe, model-agnostic through configs/models/<name>.json.

Kept from 001 (which kept them from the pilot):
  - chat rendering with the model's template and chat_template_kwargs (thinking off); loss on the assistant story
    tokens + the end-of-turn token; prompt (incl. empty think block / thought channel) and trailing newline masked
  - LoRA r32 / alpha 64 / dropout 0 on the config's target modules; AdamW(0.9, 0.999, eps 1e-8, wd 0); lr 5e-4
  - linear warmup (10 steps) then cosine decay to 0 (001's deliberate deviation from the pilot's constant LR)
  - effective batch 32 = micro 4 x accum 8; one epoch; data order = random.seed(seed); random.shuffle(range(N))
  - loss = summed token CE over the effective batch / number of supervised tokens in the effective batch; clip 1.0
  - logits only at supervised positions, in chunks; bf16 lm_head output cast to fp32 before CE
  - snapshots at steps 25, 62, 125, 188 and final
New in the portable version:
  - final-logit softcapping (Gemma) applied in the chunked loss, and a forward check before training that compares
    the chunked loss with the HF model's own forward (catches a wrong backbone path or a missing softcap)
  - --max_steps also saves the adapter at the last step (smoke runs produce a loadable adapter)
Replay (006): --replay FILE adds round(eff_bs * replay_ratio) chat rows (same row format) to every step on top of the
eff_bs story rows; story order stays identical. Replay rows must be generated by THIS model's parent.

python -m si_pipeline.train --model_config qwen3_32b --data A --seed 0 [--out DIR] [--dry] [--max_steps 5]
"""
import argparse, json, math, os, random, time

from si_pipeline.common import ChatFormat, add_common_args, load_model_config, load_paths, load_tokenizer, \
    logit_softcap, lora_target, resolve_model_dir, runs, sha256
from si_pipeline.data_files import story_path


def load_rows(path):
    return [json.loads(l)["messages"] for l in open(path)]


def lr_factor(step0, warmup, total):
    """step0 = number of optimizer steps already taken. Linear warmup, then cosine decay to 0 at `total`."""
    if step0 < warmup:
        return (step0 + 1) / warmup
    p = (step0 + 1 - warmup) / max(1, total - warmup)
    return 0.5 * (1.0 + math.cos(math.pi * min(1.0, p)))


def main():
    ap = add_common_args(argparse.ArgumentParser(description=__doc__.split("\n")[0]))
    ap.add_argument("--data", required=True, help="A, B (fetched story files) or a JSONL path of {messages} rows")
    ap.add_argument("--out", default=None, help="default: <runs>/train/<model>_<data>_s<seed>")
    ap.add_argument("--seed", type=int, default=0); ap.add_argument("--lr", type=float, default=5e-4)
    ap.add_argument("--eff_bs", type=int, default=32); ap.add_argument("--micro_bs", type=int, default=None,
                                                                         help="default: model config train.micro_bs")
    ap.add_argument("--warmup", type=int, default=10)
    ap.add_argument("--schedule", default="cosine", choices=["cosine", "constant"])
    ap.add_argument("--replay", default=None); ap.add_argument("--replay_ratio", type=float, default=1.0)
    ap.add_argument("--max_steps", type=int, default=0, help="stop early (smoke/probe) and save step<N>; 0 = full epoch")
    ap.add_argument("--save_steps", default="25,62,125,188", help="extra adapter snapshots")
    ap.add_argument("--dry", action="store_true", help="render + count tokens only (tokenizer only, no GPU)")
    ap.add_argument("--loss_chunk", type=int, default=None, help="supervised positions per lm_head chunk")
    ap.add_argument("--max_pad_tok", type=int, default=6000, help="replay micro-batch padded-token cap (memory only)")
    ap.add_argument("--no_grad_ckpt", action="store_true", help="disable gradient checkpointing (falls back on OOM)")
    ap.add_argument("--pack_tok", type=int, default=0,
                    help="if > 0: micro-batches = length-sorted rows packed under this padded-token cap")
    ap.add_argument("--skip_forward_check", action="store_true")
    args = ap.parse_args()

    mcfg, paths = load_model_config(args.model_config), load_paths(args.paths)
    tc = mcfg.get("train", {})
    args.micro_bs = args.micro_bs or tc.get("micro_bs", 4)
    args.loss_chunk = args.loss_chunk or tc.get("loss_chunk", 4096)
    lcfg = mcfg["lora"]
    data_path = story_path(paths, args.data)
    tag = args.data if not os.path.exists(args.data) else os.path.basename(args.data).replace(".jsonl", "")
    args.out = args.out or runs(paths, "train", f"{mcfg['name']}_{tag}_s{args.seed}")
    os.makedirs(args.out, exist_ok=True)
    random.seed(args.seed)

    tok = load_tokenizer(mcfg, paths)
    fmt = ChatFormat(mcfg, tok)
    import torch
    torch.manual_seed(args.seed)
    from torch.nn.utils.rnn import pad_sequence
    enc = [tuple(torch.tensor(x) for x in fmt.encode_train(m)) for m in load_rows(data_path)]
    n_loss_tok = sum(int((l != -100).sum()) for _, l in enc)
    order = list(range(len(enc))); random.shuffle(order)  # identical to 001 / the pilot for the same seed
    n_steps = math.ceil(len(order) / args.eff_bs)

    rep_enc, rep_order, n_rep_per_step = [], [], 0
    if args.replay:
        rep_enc = [tuple(torch.tensor(x) for x in fmt.encode_train(m)) for m in load_rows(args.replay)]
        n_rep_per_step = round(args.eff_bs * args.replay_ratio)
        rng = random.Random(10_000 + args.seed)  # separate stream: story order stays identical
        need = n_rep_per_step * n_steps
        while len(rep_order) < need:
            perm = list(range(len(rep_enc))); rng.shuffle(perm); rep_order += perm
        rep_order = rep_order[:need]
    n_rep_loss_tok = sum(int((rep_enc[i][1] != -100).sum()) for i in rep_order) if rep_order else 0

    meta = dict(model_config=mcfg["name"], model=mcfg["hf_id"], revision=mcfg["revision"],
                data=data_path, data_sha256=sha256(data_path), n_examples=len(enc), n_loss_tokens=n_loss_tok,
                replay=args.replay, replay_sha256=sha256(args.replay) if args.replay else None,
                replay_rows=len(rep_enc), replay_per_step=n_rep_per_step, replay_loss_tokens_seen=n_rep_loss_tok,
                lr=args.lr, rank=lcfg["r"], alpha=lcfg["alpha"], dropout=lcfg["dropout"], eff_bs=args.eff_bs,
                micro_bs=args.micro_bs, accum=args.eff_bs // args.micro_bs, epochs=1, steps=n_steps,
                max_steps=args.max_steps, warmup=args.warmup,
                schedule=("linear warmup then cosine decay to 0" if args.schedule == "cosine"
                          else "linear warmup then constant"),
                optimizer="AdamW(0.9,0.999,eps=1e-8,wd=0)", grad_clip=1.0, seed=args.seed,
                targets=lora_target(mcfg), chat_kw=fmt.kw, render_mode=fmt.mode, eot_token=fmt.eot,
                loss_mask="assistant content + end-of-turn token; prompt (incl. empty think/thought block) and text "
                          "after the end-of-turn token masked",
                loss_norm="sum CE over supervised tokens in the optimizer step / their count",
                torch=torch.__version__, gradient_checkpointing=not args.no_grad_ckpt, pack_tok=args.pack_tok,
                loss_chunk=args.loss_chunk, first_order_idx=order[:8])
    json.dump(meta, open(f"{args.out}/train_meta.json", "w"), indent=1)
    print(json.dumps({k: v for k, v in meta.items() if k != "targets"}), flush=True)

    with open(f"{args.out}/golden_render.jsonl", "w") as g:  # rendered examples for inspection
        for src, i in [(enc, i) for i in order[:3]] + [(rep_enc, i) for i in rep_order[:2]]:
            ids, lab = src[i]
            g.write(json.dumps(dict(idx=i, n_tok=len(ids), n_sup=int((lab != -100).sum()),
                                    masked_tail=tok.decode(ids[lab == -100])[-200:],
                                    trained_head=tok.decode(ids[lab != -100])[:200],
                                    trained_tail=tok.decode(ids[lab != -100])[-60:])) + "\n")
    if args.dry:
        return

    import transformers
    from transformers import AutoModelForCausalLM
    from peft import LoraConfig, get_peft_model
    model_dir = resolve_model_dir(mcfg, paths)
    meta.update(model_dir=model_dir, transformers=transformers.__version__)
    kw = dict(dtype=getattr(torch, mcfg.get("dtype", "bfloat16")), device_map="cuda")
    if tc.get("attn_implementation"):
        kw["attn_implementation"] = tc["attn_implementation"]
    model = AutoModelForCausalLM.from_pretrained(model_dir, **kw)
    meta["hf_class"] = type(model).__name__
    model.config.use_cache = False
    if not args.no_grad_ckpt:
        model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
    model.enable_input_require_grads()
    model = get_peft_model(model, LoraConfig(r=lcfg["r"], lora_alpha=lcfg["alpha"], lora_dropout=lcfg["dropout"],
                                             target_modules=lora_target(mcfg), task_type="CAUSAL_LM"))
    params = [p for p in model.parameters() if p.requires_grad]
    meta["trainable_params"] = sum(p.numel() for p in params)
    meta["lora_modules"] = sum(1 for n, _ in model.named_modules() if n.endswith(".lora_A"))
    json.dump(meta, open(f"{args.out}/train_meta.json", "w"), indent=1)
    print(f"{meta['hf_class']}: {meta['lora_modules']} LoRA modules, {meta['trainable_params']:,} trainable params",
          flush=True)
    opt = torch.optim.AdamW(params, lr=args.lr, betas=(0.9, 0.999), eps=1e-8, weight_decay=0.0)
    fn = (lambda s: lr_factor(s, args.warmup, n_steps)) if args.schedule == "cosine" else \
        (lambda s: min(1.0, (s + 1) / args.warmup))
    sched = torch.optim.lr_scheduler.LambdaLR(opt, fn)

    inner = model.base_model.model  # the HF *ForCausalLM / *ForConditionalGeneration
    decoder, lm_head = inner.model, inner.get_output_embeddings()
    cap = logit_softcap(inner.config)
    meta["final_logit_softcapping"] = cap
    pad_id = tok.pad_token_id if tok.pad_token_id is not None else fmt.eot_id

    def collate(items):
        ids = pad_sequence([x[0] for x in items], batch_first=True, padding_value=pad_id).cuda()
        lab = pad_sequence([x[1] for x in items], batch_first=True, padding_value=-100).cuda()
        att = pad_sequence([torch.ones_like(x[0]) for x in items], batch_first=True, padding_value=0).cuda()
        return ids, lab, att

    def logits_of(h):
        z = lm_head(h).float()
        return cap * torch.tanh(z / cap) if cap else z

    def micro_loss_sum(items, per_token=False):
        ids, lab, att = collate(items)
        h = decoder(input_ids=ids, attention_mask=att).last_hidden_state  # [B, T, d]
        tgt = lab[:, 1:]
        sel = tgt != -100
        hs = h[:, :-1][sel]  # [n_sup, d], positions predicting supervised tokens
        ts = tgt[sel]
        total = h.new_zeros((), dtype=torch.float32)
        per = []
        for c in range(0, hs.size(0), args.loss_chunk):
            ce = torch.nn.functional.cross_entropy(logits_of(hs[c:c + args.loss_chunk]), ts[c:c + args.loss_chunk],
                                                   reduction="none")
            total = total + ce.sum()
            if per_token:
                per.append(ce.detach())
        return (total, int(sel.sum()), torch.cat(per)) if per_token else (total, int(sel.sum()))

    if not args.skip_forward_check:  # chunked-loss path vs the HF model's own forward (incl. softcap), one row
        with torch.no_grad():
            row = [enc[order[0]]]
            ids, lab, att = collate(row)
            ref = inner(input_ids=ids, attention_mask=att).logits[:, :-1].float()
            sel = lab[:, 1:] != -100
            ref_nll = torch.nn.functional.cross_entropy(ref[sel], lab[:, 1:][sel], reduction="none")
            _, n, our_nll = micro_loss_sum(row, per_token=True)
            d = (ref_nll - our_nll).abs()
            fc = dict(n_tokens=n, nll_hf=float(ref_nll.mean()), nll_chunked=float(our_nll.mean()),
                      mean_abs_diff=float(d.mean()), max_abs_diff=float(d.max()))
            del ref
        meta["forward_check"] = fc
        json.dump(meta, open(f"{args.out}/train_meta.json", "w"), indent=1)
        print("forward check (HF forward vs chunked loss path):", fc, flush=True)
        assert fc["mean_abs_diff"] < 0.02, "chunked loss path disagrees with the HF forward -- check backbone/softcap"
        torch.cuda.empty_cache()

    def pack(g, max_rows, cap_tok):  # g is length-sorted; greedy packing under rows x max_len <= cap
        out, cur = [], []
        for x in g:
            if cur and (len(cur) == max_rows or (len(cur) + 1) * len(x[0]) > cap_tok):
                out.append(cur); cur = []
            cur.append(x)
        if cur:
            out.append(cur)
        return out

    def biggest_mb(cap_tok):
        best, bsz = None, -1
        for st in range(n_steps):
            its = [enc[i] for i in order[st * args.eff_bs:(st + 1) * args.eff_bs]]
            grs = [sorted(its, key=lambda x: len(x[0]))]
            if n_rep_per_step:
                grs.append(sorted([rep_enc[i] for i in rep_order[st * n_rep_per_step:(st + 1) * n_rep_per_step]],
                                  key=lambda x: len(x[0])))
            for g in grs:
                for mb in pack(g, args.micro_bs, cap_tok):
                    sz = len(mb) * max(len(x[0]) for x in mb)
                    if sz > bsz:
                        best, bsz = mb, sz
        return best, bsz

    if args.no_grad_ckpt:  # memory probe: largest micro-batch of the run, keep the largest cap leaving >= 15 GB free
        total = torch.cuda.get_device_properties(0).total_memory / 1e9
        chosen = None
        for cap_tok in [c for c in (8192, 6144, 4096, 3072, 2048) if c <= max(args.pack_tok, 2048)]:
            mb, bsz = biggest_mb(cap_tok)
            try:
                torch.cuda.reset_peak_memory_stats()
                ls, _ = micro_loss_sum(mb); ls.backward()
                peak = torch.cuda.max_memory_allocated() / 1e9
                print(f"probe cap {cap_tok}: biggest micro-batch {bsz} padded tokens, peak {peak:.1f} GB of {total:.0f}",
                      flush=True)
                ok = peak < total - 15
            except torch.OutOfMemoryError:
                print(f"probe cap {cap_tok}: OOM", flush=True); ok = False
            opt.zero_grad(set_to_none=True); torch.cuda.empty_cache()
            if ok:
                chosen = cap_tok; break
        if chosen is None:
            print("no cap fits without checkpointing -> enabling gradient checkpointing, cap 6000", flush=True)
            model.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
            chosen = 6000; meta["grad_ckpt"] = True
        else:
            meta["grad_ckpt"] = False
        args.pack_tok = chosen; meta["pack_tok"] = chosen
        json.dump(meta, open(f"{args.out}/train_meta.json", "w"), indent=1)

    save_steps = {int(s) for s in args.save_steps.split(",") if s}
    log = open(f"{args.out}/train_log.jsonl", "w")
    model.train(); t0 = time.time()
    for step in range(n_steps):
        items = [enc[i] for i in order[step * args.eff_bs:(step + 1) * args.eff_bs]]
        n_story = len(items)
        if n_rep_per_step:
            items += [rep_enc[i] for i in rep_order[step * n_rep_per_step:(step + 1) * n_rep_per_step]]
        tot_tok = sum(int((x[1] != -100).sum()) for x in items)
        story_tok = sum(int((x[1] != -100).sum()) for x in items[:n_story])
        lr_used = opt.param_groups[0]["lr"]
        loss_acc, story_loss, seen = 0.0, 0.0, 0
        # micro-batches = length-sorted chunks of the step's rows (stories and replay grouped separately); the step's
        # row set and the token-sum normalisation are unchanged, so the gradient is the same up to summation order
        groups = [sorted(items[:n_story], key=lambda x: len(x[0]))]
        if len(items) > n_story:
            groups.append(sorted(items[n_story:], key=lambda x: len(x[0])))
        for gi, g in enumerate(groups):
            mbs = [g[m:m + args.micro_bs] for m in range(0, len(g), args.micro_bs)]
            if args.pack_tok:
                mbs = pack(g, args.micro_bs, args.pack_tok)
            elif gi == 1:  # replay rows: at most micro_bs rows AND at most max_pad_tok padded tokens per micro-batch
                mbs = pack(g, args.micro_bs, args.max_pad_tok)
            for mb in mbs:
                lsum, n = micro_loss_sum(mb)
                (lsum / tot_tok).backward()
                loss_acc += lsum.item(); seen += n
                if gi == 0:
                    story_loss += lsum.item()
        assert seen == tot_tok, (seen, tot_tok)
        gn = torch.nn.utils.clip_grad_norm_(params, 1.0)
        opt.step(); sched.step(); opt.zero_grad(set_to_none=True)
        rec = dict(step=step + 1, loss=loss_acc / tot_tok, story_loss=story_loss / story_tok,
                   grad_norm=float(gn), lr=lr_used, elapsed=round(time.time() - t0, 1), tokens=tot_tok,
                   story_tokens=story_tok, peak_gb=round(torch.cuda.max_memory_allocated() / 1e9, 1))
        log.write(json.dumps(rec) + "\n"); log.flush()
        if (step + 1) % 5 == 0 or step < 3:
            print(rec, flush=True)
        if (step + 1) in save_steps and step + 1 < n_steps:
            model.save_pretrained(f"{args.out}/step{step + 1:03d}")
        if args.max_steps and step + 1 >= args.max_steps:
            model.save_pretrained(f"{args.out}/step{step + 1:03d}")
            break
    if not args.max_steps:
        model.save_pretrained(f"{args.out}/final")
    print("done", round(time.time() - t0, 1), flush=True)


if __name__ == "__main__":
    main()
